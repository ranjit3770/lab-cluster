import * as React from "react"

import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & {
    interactive?: boolean
    variant?: "default" | "bordered" | "ghost"
  }
>(({ className, interactive, variant = "default", ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl bg-card text-card-foreground transition-all duration-200",
      variant === "default" && "border border-border/50 shadow-sm",
      variant === "bordered" && "border border-border bg-transparent",
      variant === "ghost" && "bg-transparent",
      interactive && "hover:border-primary/30 hover:shadow-md cursor-pointer",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

